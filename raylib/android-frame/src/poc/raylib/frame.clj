(ns poc.raylib.frame
  "Fixed first-frame Jolt -> jolt.ffi -> Raylib rendering gate.

  Only scalar arguments cross this boundary. Color uses the packed uint32
  representation already validated by the pinned raylib-jlt desktop baseline."
  (:require [jolt.ffi :as ffi]))

(declare init-window set-target-fps close-window should-close-raw
         begin-drawing end-drawing clear-background draw-text)

(ffi/defcfn init-window "InitWindow" [:int :int :string] :void)
(ffi/defcfn set-target-fps "SetTargetFPS" [:int] :void)
(ffi/defcfn ^:private should-close-raw "WindowShouldClose" [] :int)
(ffi/defcfn begin-drawing "BeginDrawing" [] :void)
(ffi/defcfn end-drawing "EndDrawing" [] :void)
(ffi/defcfn clear-background "ClearBackground" [:uint] :void)
(ffi/defcfn draw-text "DrawText" [:string :int :int :int :uint] :void)
(ffi/defcfn close-window "CloseWindow" [] :void)

(defn rgba [r g b a]
  (bit-or (int r) (bit-shift-left (int g) 8)
          (bit-shift-left (int b) 16) (bit-shift-left (int a) 24)))

(def RAYWHITE (rgba 245 245 245 255))
(def DARKBLUE (rgba 0 82 172 255))
(def DARKGRAY (rgba 80 80 80 255))
(def MAROON (rgba 190 33 55 255))

(defn window-should-close? []
  (not (zero? (bit-and (should-close-raw) 0xff))))

(defn first-frame! []
  (let [frame-count 120]
    (init-window 0 0 "Jolt Raylib first frame")
    (set-target-fps 30)
    (try
      (loop [frame 0]
        (when (and (< frame frame-count) (not (window-should-close?)))
          (begin-drawing)
          (clear-background RAYWHITE)
          (draw-text "Jolt + Raylib Android" 24 48 30 DARKBLUE)
          (draw-text "Frame generated by Jolt through jolt.ffi" 24 92 20 DARKGRAY)
          (draw-text (str "Frame: " frame " / " frame-count) 24 132 22 MAROON)
          (draw-text "Jolt/Chez + Raylib 6.1-dev | API 35 | arm64-v8a" 24 172 16 DARKGRAY)
          (end-drawing)
          (recur (inc frame))))
      frame-count
      (finally (close-window)))))

(ffi/export! "raylib_first_frame" first-frame! [] :int)
